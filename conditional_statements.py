# Example 1 (if-else)
a = 13

if a > 10:
    print(f"{a} is greater than 10")
else:
    print(f"{a} is lesser than 10")


# Example 2 (if-elif-else)
color = input("Enter your choice of colors between 'red' or 'pink': ")
if color == "red":
    print("You have chosen red!")
elif color == "pink":
    print("You have chosen pink!")
else:
    print("Invalid color input!")
