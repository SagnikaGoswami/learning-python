# Integer
a = 12
print(a)
print(type(a)) # class <'int'>

b = -24
print(b)
print(type(b))


# Float
c = 56.8
print(c)
print(type(c)) # class <'float'>

d = 12/3 # 4.0, float
print(d)
print(type(d))


# Complex (real, imaginary)
e = 34j
print(e)
print(type(e)) # class <'complex'>


# Strings
str1 = '1231232323@#6878'
print(str1)
print(type(str1)) # class <'str'>


# Boolean
is_follow = True
print(is_follow)
print(type(is_follow)) # <class 'bool'>
